
from database.connection import DatabaseConnection


def createTables():
    db_config = None
    cursor = None

    try:
        db_config = DatabaseConnection()
        cursor = db_config.cursor()

        users_table_query = """
        CREATE TABLE IF NOT EXISTS users (
            user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR(100) NOT NULL,
            email VARCHAR(100) NOT NULL UNIQUE,
            hashpassword VARCHAR(255) NOT NULL,
            role VARCHAR(20) DEFAULT 'user'
                CHECK (role IN ('admin', 'user')),
            phone VARCHAR(15),
            dateofbirth DATE,
            profilename VARCHAR(255),
            profilepath VARCHAR(255),
            is_active BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """

        products_table_query = """
        CREATE TABLE IF NOT EXISTS products (
            product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            product_name VARCHAR(150) NOT NULL,
            description TEXT,
            quantity INTEGER DEFAULT 0 CHECK (quantity >= 0),
            category VARCHAR(100),
            imgname VARCHAR(255),
            buyprice NUMERIC(15,2) DEFAULT 0.00,
            saleprice NUMERIC(15,2) DEFAULT 0.00,
            storedpath VARCHAR(255),
            is_active BOOLEAN DEFAULT TRUE,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """

        orders_table_query = """
        CREATE TABLE IF NOT EXISTS orders (
            order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT REFERENCES users(user_id),
            status VARCHAR(20) DEFAULT 'pending'
                CHECK (status IN (
                    'shipped', 'delivered', 'cancelled', 'pending'
                )),
            address VARCHAR(255),
            total NUMERIC(15,2) DEFAULT 0.00,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """

        orderdetails_table_query = """
        CREATE TABLE IF NOT EXISTS orderdetails (
            order_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            order_id BIGINT REFERENCES orders(order_id),
            product_id BIGINT REFERENCES products(product_id),
            quantity INTEGER DEFAULT 1 CHECK (quantity > 0),
            price NUMERIC(15,2) DEFAULT 0.00,
            subtotal NUMERIC(20,2)
                GENERATED ALWAYS AS (quantity * price) STORED
        )
        """

        payment_table_query = """
        CREATE TABLE IF NOT EXISTS payment (
            payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT REFERENCES users(user_id),
            order_id BIGINT REFERENCES orders(order_id),
            method VARCHAR(20)
                CHECK (method IN ('cash', 'upi', 'netbanking', 'razorpay')),
            amount NUMERIC(20,2) DEFAULT 0.00,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            status VARCHAR(100),
            razorpay_id VARCHAR(100),
            razorpay_order_id VARCHAR(255),
            razorpay_payment_id VARCHAR(255)
        )
        """

        cart_table_query = """
        CREATE TABLE IF NOT EXISTS cart (
            cartid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            userid BIGINT REFERENCES users(user_id),
            productid BIGINT REFERENCES products(product_id),
            quantity INTEGER DEFAULT 1 CHECK (quantity > 0)
        )
        """

        tables = [
            users_table_query,
            products_table_query,
            orders_table_query,
            orderdetails_table_query,
            payment_table_query,
            cart_table_query
        ]

        for query in tables:
            cursor.execute(query)

        db_config.commit()

        return "Tables Created Successfully"

    except Exception as e:
        if db_config:
            db_config.rollback()

        return f"Database Error: {e}"

    finally:
        if cursor:
            cursor.close()

        if db_config:
            db_config.close()
if __name__ == "__main__":
    print(createTables())